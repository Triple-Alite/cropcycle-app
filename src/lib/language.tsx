export function translateText(text: string, language: AppLanguage) {
  if (language === "EN") return text;
  const exact = translations[language][text.trim()];
  if (exact !== undefined) return `${text.match(/^\s*/)?.[0] ?? ""}${exact}${text.match(/\s*$/)?.[0] ?? ""}`;
  const dynamicPatterns: Array<[RegExp, (match: RegExpMatchArray) => string]> = language === "YO"
    ? [
      [/^(\d+) saved assessments$/, (match) => `${match[1]} àyẹ̀wò tí a fì pamọ́`],
      [/^(\d+) of (\d+) farmers$/, (match) => `${match[1]} nínú àwọn àgbẹ̀ ${match[2]}`],
      [/^(\d+) farm(s?) in your workspace\.$/, (match) => `${match[1]} ${match[1] === "1" ? "oko" : "oko"} nínú ibi iṣẹ́ rẹ.`],
      [/^(\d+) soil (reading|readings) cleared\.$/, (match) => `A pa ìwọ̀n ilẹ̀ ${match[1]} rẹ́.`],
    ]
    : [
      [/^(\d+) saved assessments$/, (match) => `${match[1]} tantancewa da aka adana`],
      [/^(\d+) of (\d+) farmers$/, (match) => `${match[1]} cikin manoma ${match[2]}`],
      [/^(\d+) farm(s?) in your workspace\.$/, (match) => `Gona ${match[1]} a wurin aikinka.`],
      [/^(\d+) soil (reading|readings) cleared\.$/, (match) => `An share ma'aunin ƙasa ${match[1]}.`],
    ];
  for (const [pattern, render] of dynamicPatterns) {
    const match = text.match(pattern);
    if (match) return render(match);
  }
  return text;
}

type LocalizableProps = {
  children?: ReactNode;
  placeholder?: string;
  "aria-label"?: string;
  title?: string;
  alt?: string;
};

function translateNode(node: ReactNode, language: AppLanguage): ReactNode {
  if (typeof node === "string") return translateText(node, language);
  if (Array.isArray(node)) return node.map((child) => translateNode(child, language));
  if (!isValidElement(node)) return node;

  const element = node as ReactElement<LocalizableProps>;
  const props: LocalizableProps = { ...element.props };
  if (props.children !== undefined) props.children = translateNode(props.children, language);
  for (const attribute of ["placeholder", "aria-label", "title", "alt"] as const) {
    if (typeof props[attribute] === "string") {
      props[attribute] = translateText(props[attribute], language);
    }
  }
  return cloneElement(element, props);
}

